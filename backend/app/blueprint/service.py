@job_handler("apply_blueprint")
def apply_blueprint_job(db: Session, job: Job) -> dict[str, Any]:
    from app.services.ingest import create_version, generate_workbook

    rec = db.get(BlueprintRecord, job.payload["blueprint_id"])
    if rec is None:
        raise NotFound("Blueprint not found.")
    if rec.status != "draft":
        raise Conflict(f"Blueprint is already {rec.status}.")
    src = db.get(Source, rec.source_id)
    bp = Blueprint.model_validate(rec.content)
    contexts = {c.dataset_id: c for c in load_contexts(db, src, with_raw=True)}
    for plan in bp.datasets:
        ctx = contexts.get(plan.dataset_id)
        if ctx is None or ctx.version != plan.version:
            raise Conflict("The data changed since this blueprint was generated; regenerate it before applying.")
    pending = [i for p in bp.datasets for i in (*p.operations, *p.columns) if i.status == "proposed"]
    results = []
    for plan in bp.datasets:
        ds = db.get(Dataset, plan.dataset_id)
        t, oplog = execute_plan(plan, contexts[plan.dataset_id], rec.id)
        v = create_version(db, ds, t, src.id)
        if plan.title and plan.title != ds.name:
            ds.name = plan.title[:300]
        results.append({"dataset_id": ds.id, "version": v.version, "row_count": v.row_count, "operations": oplog})
    db.flush()
    # KPIs re-evaluated on the new versions (deterministic) and stored with the blueprint
    new_ctx = load_contexts(db, src)
    evaluate_all(bp, new_ctx)
    rec.content = bp.model_dump(mode="json")
    rec.status = "applied"
    rec.applied_at = utcnow()
    rec.applied_by = job.created_by
    db.commit()
    art = generate_workbook(db, src, user_id=job.created_by)
    rec.result = {"datasets": results, "artifact_id": art.id, "unreviewed_items_skipped": len(pending)}
    audit(db, "blueprint.applied", workspace_id=rec.workspace_id, actor_id=job.created_by, target_type="blueprint",
          target_id=rec.id, details={"datasets": [{k: r[k] for k in ("dataset_id", "version", "row_count")} for r in results],
                                     "artifact_id": art.id})
    db.commit()
    return {"blueprint_id": rec.id, **rec.result}


def latest_applied(db: Session, source_id: int) -> Blueprint | None:
    rec = db.execute(
        select(BlueprintRecord).where(BlueprintRecord.source_id == source_id, BlueprintRecord.status == "applied")
        .order_by(BlueprintRecord.number.desc())
    ).scalars().first()
    return Blueprint.model_validate(rec.content) if rec else None


