TERMINAL = ("applied", "superseded")


def evaluate_all(bp: Blueprint, contexts: list[DatasetContext]) -> list[str]:
    warnings: list[str] = []
    by_id = {c.dataset_id: c for c in contexts}
    for plan in bp.datasets:
        if plan.dataset_id in by_id:
            warnings += evaluate_kpis(plan.kpis, by_id[plan.dataset_id])
    return warnings


def build_blueprint(source: Source, contexts: list[DatasetContext], requirements: str | None = None) -> Blueprint:
    bp = rules_blueprint(source.id, contexts)
    info = GeneratorInfo(engine="rules")
    reason = ai_mod.not_configured_reason()
    if reason:
        info.fallback_reason = f"{reason}; generated by deterministic rules."
    else:
        try:
            payload = ai_mod.build_payload(contexts, bp, requirements)
            res = ai_mod.interpret(payload)
            bp, warnings = merge_ai(bp, res.interpretation, contexts)
            info = GeneratorInfo(engine="ai", model=res.model, attempts=res.attempts, warnings=warnings,
                                 input_tokens=res.input_tokens, output_tokens=res.output_tokens)
        except ai_mod.AIUnavailable as e:
            info.fallback_reason = f"{e} Generated by deterministic rules instead."
            log.warning("blueprint_ai_fallback", source_id=source.id, reason=str(e))
        except Exception as e:  # never let an AI-side bug block the user
            info.fallback_reason = f"AI interpretation failed unexpectedly ({type(e).__name__}); generated by deterministic rules instead."
            log.error("blueprint_ai_crash", source_id=source.id, error=repr(e))
    info.warnings += evaluate_all(bp, contexts)
    bp.generator = info
    return Blueprint.model_validate(bp.model_dump())


@job_handler("generate_blueprint")
def generate_blueprint_job(db: Session, job: Job) -> dict[str, Any]:
    src = db.get(Source, job.payload["source_id"])
    if src is None or src.status != "ready":
        raise NotFound("Source not found or not ready.")
    contexts = load_contexts(db, src)
    bp = build_blueprint(src, contexts, job.payload.get("requirements"))
    for old in db.execute(select(BlueprintRecord).where(BlueprintRecord.source_id == src.id, BlueprintRecord.status == "draft")).scalars():
        old.status = "superseded"
    number = (db.execute(select(func.max(BlueprintRecord.number)).where(BlueprintRecord.source_id == src.id)).scalar() or 0) + 1
    rec = BlueprintRecord(workspace_id=src.workspace_id, source_id=src.id, number=number, status="draft",
                          engine=bp.generator.engine, content=bp.model_dump(mode="json"),
                          requirements=job.payload.get("requirements"), created_by=job.created_by)
    db.add(rec)
    db.flush()
    audit(db, "blueprint.generated", workspace_id=src.workspace_id, actor_id=job.created_by, target_type="blueprint",
          target_id=rec.id, details={"source_id": src.id, "engine": bp.generator.engine, "fallback_reason": bp.generator.fallback_reason})
    db.commit()
    return {"blueprint_id": rec.id, "engine": bp.generator.engine}


