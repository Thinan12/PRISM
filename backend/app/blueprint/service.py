class Edit(BaseModel):
    model_config = ConfigDict(extra="forbid")
    action: Literal["approve", "reject", "remove", "update", "add", "approve_all"]
    target: Literal["column", "operation", "kpi", "relationship", "assumption", "panel", "blueprint"]
    dataset_id: int | None = None
    id: str | None = Field(default=None, max_length=100)
    changes: dict[str, Any] | None = None


class EditError(PrismError):
    code = "invalid_edit"
    status_code = 422


def _find(items: list, id_: str | None, attr: str = "id"):
    for it in items:
        if getattr(it, attr) == id_:
            return it
    raise EditError(f"Item '{id_}' not found.")


def _items(bp: Blueprint, e: Edit) -> list:
    if e.target in ("relationship", "assumption", "panel"):
        return {"relationship": bp.relationships, "assumption": bp.assumptions, "panel": bp.dashboard}[e.target]
    if e.dataset_id is None:
        raise EditError(f"dataset_id is required for {e.target} edits.")
    try:
        plan = bp.dataset(e.dataset_id)
    except KeyError as ex:
        raise EditError("Unknown dataset.") from ex
    return {"column": plan.columns, "operation": plan.operations, "kpi": plan.kpis}[e.target]


def _update(item: Any, target: str, ch: dict[str, Any]) -> None:
    allowed = {
        "column": {"display_name", "description", "semantic_role"},
        "operation": {"title", "mappings", "to_type"},
        "kpi": {"name", "description", "aggregation", "column", "filter"},
        "assumption": {"text"},
        "panel": {"title", "chart"},
        "relationship": set(),
    }[target]
    bad = set(ch) - allowed
    if bad:
        raise EditError(f"Fields not editable on {target}: {sorted(bad)}")
    for k, v in ch.items():
        if target == "column" and k == "semantic_role":
            v = SemanticRole(v)
        if target == "column" and k == "display_name":
            v = " ".join(str(v).split())
            if not v:
                raise EditError("Display name cannot be empty.")
        if target == "kpi" and k == "aggregation":
            v = Aggregation(v)
        if target == "kpi" and k == "filter":
            v = Filter.model_validate(v) if v else None
        if target == "panel" and k == "chart":
            v = ChartKind(v)
        if target == "operation" and k == "mappings":
            if not isinstance(item.spec, OpMapValues):
                raise EditError("Only value-mapping operations have mappings.")
            item.spec.mappings = [ValueMapping.model_validate(m) for m in v]
            continue
        if target == "operation" and k == "to_type":
            if not isinstance(item.spec, OpCastColumn):
                raise EditError("Only cast operations have a target type.")
            item.spec.to_type = v
            continue
        setattr(item, k, v)
    if hasattr(item, "origin") and target != "relationship":
        item.origin = "user"


def apply_edits(bp: Blueprint, edits: list[Edit], contexts: list[DatasetContext]) -> Blueprint:
    bp = bp.model_copy(deep=True)
    for e in edits:
        if e.action == "approve_all":
            for plan in bp.datasets:
                for it in [*plan.columns, *plan.operations, *plan.kpis]:
                    if it.status == "proposed":
                        it.status = "approved"
            for it in [*bp.relationships, *bp.assumptions, *bp.dashboard]:
                if it.status == "proposed":
                    it.status = "approved"
            continue
        if e.action == "add":
            if e.target != "kpi" or e.dataset_id is None or not e.changes:
                raise EditError("Only KPIs can be added (with dataset_id and changes).")
            plan = bp.dataset(e.dataset_id)
            data = {"confidence": 1.0, "origin": "user", "status": "approved", **e.changes}
            data["id"] = f"k{e.dataset_id}-u{len(plan.kpis) + 1}"
            try:
                plan.kpis.append(Kpi.model_validate(data))
            except ValidationError as ex:
                raise EditError(f"Invalid KPI: {ex.errors()[0]['msg']}") from ex
            continue
        items = _items(bp, e)
        item = _find(items, e.id, "key" if e.target == "column" else "id")
        if e.action in ("approve", "reject"):
            item.status = "approved" if e.action == "approve" else "rejected"
        elif e.action == "remove":
            if e.target == "column":
                raise EditError("Columns cannot be removed from a blueprint; add an exclude operation instead.")
            items.remove(item)
        elif e.action == "update":
            _update(item, e.target, e.changes or {})
    try:
        bp = Blueprint.model_validate(bp.model_dump())
    except ValidationError as ex:
        raise EditError("; ".join(err["msg"] for err in ex.errors())[:500]) from ex
    # KPIs rejected for being invalid are reported, not silently dropped
    bp.generator.warnings = [w for w in bp.generator.warnings if not w.startswith("KPI '")] + evaluate_all(bp, contexts)
    return bp


def get_record(db: Session, workspace_id: int, blueprint_id: int) -> BlueprintRecord:
    rec = db.get(BlueprintRecord, blueprint_id)
    if rec is None or rec.workspace_id != workspace_id:
        raise NotFound("Blueprint not found.")
    return rec


def edit_blueprint(db: Session, rec: BlueprintRecord, edits: list[Edit], user_id: int) -> BlueprintRecord:
    if rec.status != "draft":
        raise Conflict(f"Blueprint is {rec.status}; generate a new one to make changes.")
    src = db.get(Source, rec.source_id)
    contexts = load_contexts(db, src)
    bp = apply_edits(Blueprint.model_validate(rec.content), edits, contexts)
    rec.content = bp.model_dump(mode="json")
    audit(db, "blueprint.edited", workspace_id=rec.workspace_id, actor_id=user_id, target_type="blueprint", target_id=rec.id,
          details={"edits": [e.model_dump(exclude_none=True) for e in edits][:50]})
    db.commit()
    db.refresh(rec)
    return rec


